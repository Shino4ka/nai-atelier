  let language = 'ru';
  try {
    const saved = localStorage.getItem('atelier-language');
    language = requested === 'en' || requested === 'ru' ? requested : saved === 'en' ? 'en' : 'ru';
    if (requested === 'en' || requested === 'ru') localStorage.setItem('atelier-language', language);
  } catch {
    if (requested === 'en') language = 'en';
  }

  const english = language === 'en';
  document.documentElement.lang = language;

  function translate(text) {
    return english && Object.hasOwn(ui, text) ? ui[text] : text;
  }

  function localize(root) {
    if (!english) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      if (node.parentElement.closest('script, style, .prompt-box')) continue;
      const text = node.textContent.trim();
      const translated = translate(text);
      if (translated !== text) node.textContent = node.textContent.replace(text, translated);
    }
    for (const element of [root, ...root.querySelectorAll('[aria-label], [placeholder], [alt]')]) {
      for (const attr of ['aria-label', 'placeholder', 'alt']) {
        const value = element.getAttribute(attr);
        if (!value) continue;
        const prefix = ['Пример: ', 'Скопировать '].find(part => value.startsWith(part));
        element.setAttribute(attr, prefix ? translate(prefix) + translate(value.slice(prefix.length)) : translate(value));
      }
    }
  }

  window.atelierText = translate;
  window.atelierLocalize = localize;

